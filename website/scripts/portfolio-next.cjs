const fs = require('node:fs');
const path = require('node:path');
const { spawn } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const action = process.argv[2];
if (!['dev', 'build', 'start'].includes(action)) throw new Error('Use the declared local website commands.');
const environmentFiles = fs.readdirSync(root).filter(name => /^\.env(?:\.|$)/.test(name) && name !== '.env.example');
if (environmentFiles.length) throw new Error('This local demo does not load environment files. Move .env files out of website/ before starting.');
const extra = process.argv.slice(3);
if (extra.length && !(extra.length === 2 && ['--port', '-p'].includes(extra[0]) && /^\d{4,5}$/.test(extra[1]) && Number(extra[1]) <= 65535)) throw new Error('The local launcher accepts only an optional --port number.');
const env = {};
for (const key of ['PATH', 'Path', 'PATHEXT', 'SystemRoot', 'SYSTEMROOT', 'WINDIR', 'windir', 'TEMP', 'TMP', 'HOME', 'USERPROFILE', 'APPDATA', 'LOCALAPPDATA', 'COMSPEC', 'ComSpec']) if (process.env[key]) env[key] = process.env[key];
env.NODE_ENV = action === 'dev' ? 'development' : 'production';
env.NEXT_TELEMETRY_DISABLED = '1';
env.NODE_OPTIONS = `--require "${path.join(__dirname, 'portfolio-network-guard.cjs').replace(/\\/g, '/')}"`;
const args = [require.resolve('next/dist/bin/next'), action, ...(action === 'build' ? [] : ['--hostname', '127.0.0.1']), ...extra];
const child = spawn(process.execPath, args, { cwd: root, env, stdio: 'inherit', windowsHide: true });
child.on('exit', code => { process.exitCode = code ?? 1; });
child.on('error', () => { process.exitCode = 1; });
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => child.kill(signal));
