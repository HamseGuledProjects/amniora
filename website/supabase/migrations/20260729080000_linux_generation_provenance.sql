create table if not exists public.linux_generation_provenance (
  id bigint generated by default as identity primary key,
  lab_id uuid not null references public.labs(id) on delete cascade,
  generated_lab_id uuid null references public.generated_labs(id) on delete set null,
  user_id uuid not null references auth.users(id) on delete cascade,
  seed text not null,
  generator_version text not null,
  provenance jsonb not null,
  deterministic_hashes jsonb not null,
  accepted_asset_attempt integer not null check (accepted_asset_attempt >= 1),
  final_deterministic_hash text not null,
  created_at timestamptz not null default now(),
  unique (lab_id)
);

create index if not exists linux_generation_provenance_user_idx
  on public.linux_generation_provenance(user_id, created_at desc);

create index if not exists linux_generation_provenance_generated_lab_idx
  on public.linux_generation_provenance(generated_lab_id)
  where generated_lab_id is not null;

create index if not exists linux_generation_provenance_hash_idx
  on public.linux_generation_provenance(final_deterministic_hash);

alter table public.linux_generation_provenance enable row level security;

drop policy if exists "Users may read their own Linux generation provenance"
  on public.linux_generation_provenance;
create policy "Users may read their own Linux generation provenance"
  on public.linux_generation_provenance
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "No browser writes to Linux generation provenance"
  on public.linux_generation_provenance;
create policy "No browser writes to Linux generation provenance"
  on public.linux_generation_provenance
  for insert
  to authenticated
  with check (false);

drop policy if exists "No browser updates to Linux generation provenance"
  on public.linux_generation_provenance;
create policy "No browser updates to Linux generation provenance"
  on public.linux_generation_provenance
  for update
  to authenticated
  using (false)
  with check (false);

drop policy if exists "No browser deletes to Linux generation provenance"
  on public.linux_generation_provenance;
create policy "No browser deletes to Linux generation provenance"
  on public.linux_generation_provenance
  for delete
  to authenticated
  using (false);
