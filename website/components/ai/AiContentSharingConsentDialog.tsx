"use client";

import Link from "next/link";
import { AnimatePresence, motion, useReducedMotion } from "framer-motion";
import { Check, ShieldCheck, X } from "lucide-react";
import Button from "@/app/components/ui/Button";
import {
  AI_CONTENT_SHARING_CONSENT_COPY,
  type AiContentConsentFeature,
} from "@/lib/ai/contentSharingConsent";
import { useEffect, useId, useRef, useState } from "react";

type Props = {
  open: boolean;
  feature: AiContentConsentFeature;
  onCancel: () => void;
  onConfirm: () => void;
  isSubmitting?: boolean;
};

const focusableSelector = [
  "a[href]",
  "button:not([disabled])",
  "input:not([disabled])",
  "select:not([disabled])",
  "textarea:not([disabled])",
  '[tabindex]:not([tabindex="-1"])',
].join(",");

export function AiContentSharingConsentDialog({
  open,
  feature,
  onCancel,
  onConfirm,
  isSubmitting = false,
}: Props) {
  const [checked, setChecked] = useState(false);
  const dialogRef = useRef<HTMLDivElement | null>(null);
  const checkboxRef = useRef<HTMLInputElement | null>(null);
  const previouslyFocusedRef = useRef<HTMLElement | null>(null);
  const titleId = useId();
  const descriptionId = useId();
  const prefersReducedMotion = useReducedMotion();
  const copy = AI_CONTENT_SHARING_CONSENT_COPY;
  const actions = copy.actions[feature];
  const informationSent =
    feature === "lab_generation"
      ? [
          "A fixed synthetic investigation opens locally",
          "No new investigation is generated by an AI service",
        ]
      : feature === "linux_grading"
      ? [
          "Sample evidence and written hints stay in this local demo",
          "Automatic assessment is unavailable",
        ]
      : [
          "Your sample question stays on this computer",
          "Written example replies demonstrate the Tutor interface",
        ];

  useEffect(() => {
    if (!open) return;

    previouslyFocusedRef.current = document.activeElement as HTMLElement | null;
    // Required privacy behavior: every modal opening starts unchecked.
    // eslint-disable-next-line react-hooks/set-state-in-effect
    setChecked(false);

    const previousOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";

    window.setTimeout(() => {
      checkboxRef.current?.focus();
    }, 0);

    return () => {
      document.body.style.overflow = previousOverflow;
      previouslyFocusedRef.current?.focus();
    };
  }, [open]);

  function closeDialog() {
    if (isSubmitting) return;
    setChecked(false);
    onCancel();
  }

  function handleConfirm() {
    if (!checked || isSubmitting) return;
    onConfirm();
  }

  function handleKeyDown(event: React.KeyboardEvent<HTMLDivElement>) {
    if (event.key === "Escape") {
      event.preventDefault();
      closeDialog();
      return;
    }

    if (event.key === "Enter" && !checked) {
      event.preventDefault();
      return;
    }

    if (event.key !== "Tab") return;

    const focusable = Array.from(
      dialogRef.current?.querySelectorAll<HTMLElement>(focusableSelector) || []
    );

    if (focusable.length === 0) {
      event.preventDefault();
      dialogRef.current?.focus();
      return;
    }

    const first = focusable[0];
    const last = focusable[focusable.length - 1];

    if (event.shiftKey && document.activeElement === first) {
      event.preventDefault();
      last.focus();
    } else if (!event.shiftKey && document.activeElement === last) {
      event.preventDefault();
      first.focus();
    }
  }

  return (
    <AnimatePresence>
      {open && (
        <motion.div
          className="fixed inset-0 z-[100] flex items-center justify-center bg-slate-950/60 px-4 py-6"
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
          exit={{ opacity: 0 }}
          transition={{ duration: prefersReducedMotion ? 0 : 0.18 }}
          onMouseDown={(event) => {
            if (event.target === event.currentTarget) closeDialog();
          }}
        >
          <motion.div
            ref={dialogRef}
            role="dialog"
            aria-modal="true"
            aria-labelledby={titleId}
            aria-describedby={descriptionId}
            tabIndex={-1}
            onKeyDown={handleKeyDown}
            initial={
              prefersReducedMotion
                ? { opacity: 1 }
                : { opacity: 0, scale: 0.96, y: 14 }
            }
            animate={{ opacity: 1, scale: 1, y: 0 }}
            exit={
              prefersReducedMotion
                ? { opacity: 0 }
                : { opacity: 0, scale: 0.97, y: 10 }
            }
            transition={{ duration: prefersReducedMotion ? 0 : 0.2 }}
            className="relative max-h-[calc(100dvh-2rem)] w-full max-w-xl overflow-hidden rounded-ui-md border border-border-strong bg-surface shadow-hover outline-none"
          >
            <div className="flex items-start gap-3 border-b border-border px-5 py-4 sm:px-6">
              <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-ui-sm bg-primary-subtle text-primary">
                <ShieldCheck size={19} aria-hidden="true" />
              </div>

              <div className="min-w-0 flex-1">
                <h2 id={titleId} className="text-lg font-semibold text-heading">
                  {feature === "tutor_chat" ? "Sample Tutor replies" : "Explore the sample investigation"}
                </h2>
                <p className="mt-1 text-sm leading-5 text-text-secondary">
                  Your question stays in this local demo.
                </p>
              </div>

              <button
                type="button"
                onClick={closeDialog}
                disabled={isSubmitting}
                aria-label="Close local example notice"
                className="rounded-ui-sm p-2 text-text-muted outline-none transition hover:bg-surface-muted hover:text-text focus-visible:ring-2 focus-visible:ring-focus disabled:cursor-not-allowed disabled:opacity-50"
              >
                <X size={18} aria-hidden="true" />
              </button>
            </div>

            <div
              id={descriptionId}
              className="cyber-consent-scroll max-h-[52dvh] space-y-4 overflow-y-auto px-5 py-4 text-sm leading-6 text-text-secondary sm:px-6"
            >
              <section aria-labelledby={`${titleId}-sent`}>
                <h3 id={`${titleId}-sent`} className="text-sm font-semibold text-heading">
                  What happens locally
                </h3>
                <ul className="mt-2 space-y-2">
                  {informationSent.map((item) => (
                    <li key={item} className="flex gap-2">
                      <Check size={16} className="mt-1 shrink-0 text-primary" aria-hidden="true" />
                      <span>{item}</span>
                    </li>
                  ))}
                </ul>
              </section>

              <section className="border-t border-border pt-4" aria-labelledby={`${titleId}-sharing`}>
                <h3 id={`${titleId}-sharing`} className="text-sm font-semibold text-heading">
                  About this example
                </h3>
                <div className="mt-2 space-y-2">
                  {copy.body.slice(0, 2).map((paragraph) => (
                    <p key={paragraph}>{paragraph}</p>
                  ))}
                </div>
              </section>

              <div className="rounded-ui-sm border border-primary/20 bg-primary-subtle p-3 text-sm leading-6 text-text-secondary">
                Please avoid submitting confidential or sensitive real-world
                information. Review Amniora&apos;s{" "}
                <Link
                  href="/privacy"
                  className="font-semibold text-primary outline-none transition hover:text-primary-hover focus-visible:rounded focus-visible:ring-2 focus-visible:ring-focus"
                >
                  {copy.privacyPolicyLabel}
                </Link>{" "}
                for details about how information is handled.
              </div>
            </div>

            <div className="border-t border-border px-5 py-4 sm:px-6">
              <label className="flex cursor-pointer items-start gap-3 rounded-ui-sm border border-border bg-surface-muted p-3 transition hover:border-border-strong">
                <span className="relative mt-0.5 flex h-5 w-5 shrink-0 items-center justify-center">
                  <input
                    ref={checkboxRef}
                    type="checkbox"
                    checked={checked}
                    onChange={(event) => setChecked(event.target.checked)}
                    disabled={isSubmitting}
                    className="peer sr-only"
                  />
                  <span className="absolute inset-0 rounded border border-border-strong bg-surface transition peer-focus-visible:ring-2 peer-focus-visible:ring-focus peer-checked:border-primary peer-checked:bg-primary" />
                  <motion.span
                    initial={false}
                    animate={{ scale: checked ? 1 : 0, opacity: checked ? 1 : 0 }}
                    transition={{ duration: prefersReducedMotion ? 0 : 0.14 }}
                    className="relative text-white"
                  >
                    <Check size={14} strokeWidth={3} aria-hidden="true" />
                  </motion.span>
                </span>
                <span className="text-sm leading-6 text-text">
                  {copy.checkbox}
                </span>
              </label>

              <div className="mt-4 flex flex-col-reverse gap-2 sm:flex-row sm:justify-end">
                <Button
                  onClick={closeDialog}
                  disabled={isSubmitting}
                  variant="secondary"
                  className="w-full sm:w-auto"
                >
                  {actions.cancel}
                </Button>
                <Button
                  onClick={handleConfirm}
                  disabled={!checked || isSubmitting}
                  loading={isSubmitting}
                  loadingText={actions.submitting}
                  className="w-full sm:w-auto"
                >
                  {actions.confirm}
                </Button>
              </div>
            </div>

            <style jsx>{`
              .cyber-consent-scroll::-webkit-scrollbar {
                width: 8px;
              }
              .cyber-consent-scroll::-webkit-scrollbar-track {
                background: transparent;
              }
              .cyber-consent-scroll::-webkit-scrollbar-thumb {
                background: var(--color-border-strong);
                border-radius: 999px;
              }
            `}</style>
          </motion.div>
        </motion.div>
      )}
    </AnimatePresence>
  );
}
